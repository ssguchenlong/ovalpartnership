function catLabel(zhVal){
  const m = CAT_TRANS[zhVal];
  if(!m) return zhVal;
  const parts = m.split("|");
  const tw = parts[0], en = parts[1];
  if(I18N_CURRENT==="en") return en || zhVal;
  if(I18N_CURRENT==="zh-TW") return tw || zhVal;
  return zhVal;
}
